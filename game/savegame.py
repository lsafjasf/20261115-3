"""Save and restore a generated world.

The save file holds the master seed, the full per-stream call sequence and the
world snapshot plus fingerprints. On load the world is regenerated by replaying
every recorded call; any divergence raises ReplayMismatch.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from .rng import RandomSystem
from .world import generate_world

SAVE_VERSION = 1


def world_fingerprint(world: dict[str, Any]) -> str:
    payload = json.dumps(world, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def build_save(
    seed: int, rng: RandomSystem, world: dict[str, Any]
) -> dict[str, Any]:
    return {
        "version": SAVE_VERSION,
        "rng": rng.snapshot(),
        "world": world,
        "world_fingerprint": world_fingerprint(world),
    }


def save_game(path: str | Path, seed: int, rng: RandomSystem, world: dict[str, Any]):
    data = build_save(seed, rng, world)
    Path(path).write_text(
        json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return data


def load_game(path: str | Path) -> dict[str, Any]:
    """Replay the saved call sequence and verify both worlds match."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if data.get("version") != SAVE_VERSION:
        raise ValueError(f"unsupported save version: {data.get('version')!r}")

    if world_fingerprint(data["world"]) != data["world_fingerprint"]:
        raise ValueError("stored world failed its own fingerprint check")

    replayed_rng = RandomSystem.from_snapshot(data["rng"])
    replayed_world = generate_world(
        replayed_rng, extra_map_calls=len(data["world"]["map"]["extra_calls"])
    )
    replayed_rng.verify_replay_complete()

    stored_fp = data["world_fingerprint"]
    replayed_fp = world_fingerprint(replayed_world)
    if replayed_fp != stored_fp:
        raise ValueError(
            f"replay mismatch: {replayed_fp[:12]} != stored {stored_fp[:12]}"
        )

    return {
        "seed": data["rng"]["seed"],
        "saved_summary": data["rng"]["summary"],
        "replayed_summary": replayed_rng.summary(),
        "world": replayed_world,
        "fingerprint": replayed_fp,
    }
